"""
tests/test_tier3_convergence.py — Phase 3B Tier 3 Full Baseline
================================================================
The final convergence gate before translate() switches to the IR path.

Loads every KQL query from tests/tier3_queries.json (generated by
extract_tier3.py) and asserts that:

    normalize(SparkSQLGenerator(ast)) == normalize(IRSparkSQLGenerator(ir))

This is the same assertion as Tiers 1 and 2, now applied to the complete
353-query production baseline. Every query that passed the original
SparkSQLGenerator test suite must converge identically through the IR path.

Setup (run once):
    py tests/extract_tier3.py

Run all:
    py -m pytest tests/test_tier3_convergence.py -v

Run with failure detail:
    py -m pytest tests/test_tier3_convergence.py -v --tb=short

Track convergence rate:
    py -m pytest tests/test_tier3_convergence.py -q 2>&1 | tail -5

Convergence gate for Phase 3C (translate() flip):
    353/353 passing  +  Tiers 1+2 100%  +  Validator 100%  +  Snapshots 100%
"""

from __future__ import annotations

import json
import re
import sys
import os
from pathlib import Path

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'src'))

import pytest
from kqlbridge.parser import parse
from kqlbridge.generators.spark_sql import SparkSQLGenerator
from kqlbridge.ir import to_semantic_ir
from kqlbridge.ir.emitters.spark_ir import IRSparkSQLGenerator

TIER3_FILE = Path(__file__).parent / "tier3_queries.json"


# ─── SQL Normalizer (same as test_emitter_convergence.py) ────────────────────

def normalize_sql(sql: str) -> str:
    sql = re.sub(r'\s+', ' ', sql.strip())
    sql = sql.replace('<>', '!=')
    sql = sql.lower()
    sql = re.sub(r'\s*,\s*', ', ', sql)
    sql = re.sub(r'\s*=\s*', ' = ', sql)
    sql = re.sub(r'\s*!=\s*', ' != ', sql)
    sql = re.sub(r'\s+', ' ', sql).strip()
    return sql


# ─── Load queries ─────────────────────────────────────────────────────────────

def _load_tier3() -> list[dict]:
    if not TIER3_FILE.exists():
        return []
    return json.loads(TIER3_FILE.read_text(encoding="utf-8"))


TIER3_QUERIES = _load_tier3()


# ─── Guard: tier3_queries.json must exist ────────────────────────────────────

def test_tier3_file_exists():
    """
    tier3_queries.json must exist before Tier 3 tests run.
    If missing: py tests/extract_tier3.py
    """
    assert TIER3_FILE.exists(), (
        f"Tier 3 query file not found: {TIER3_FILE}\n"
        f"Generate it with: py tests/extract_tier3.py"
    )


def test_tier3_has_queries():
    """tier3_queries.json must contain at least 100 queries."""
    if not TIER3_FILE.exists():
        pytest.skip("tier3_queries.json not yet generated")
    queries = _load_tier3()
    assert len(queries) >= 100, (
        f"Expected >= 100 Tier 3 queries, found {len(queries)}.\n"
        f"Re-run: py tests/extract_tier3.py"
    )


def test_tier3_query_count():
    """Report the exact count — useful for convergence tracking."""
    if not TIER3_FILE.exists():
        pytest.skip("tier3_queries.json not yet generated")
    queries = _load_tier3()
